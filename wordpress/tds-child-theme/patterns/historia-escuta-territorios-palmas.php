<h2 class="wp-block-heading">TDS apresenta proposta às lideranças de Palmas e inicia escuta dos territórios</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>O Programa Territórios de Desenvolvimento Social e Inclusão Produtiva foi apresentado a presidentes de associações de moradores e lideranças comunitárias em encontro realizado no Centro de Ensino Médio de Taquaralto, em Palmas.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Segundo a publicação institucional da Prefeitura de Palmas, <strong>62 lideranças comunitárias participaram da reunião</strong>. A mesma fonte registra que a escuta das necessidades dos territórios orientaria as ações posteriores do programa.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>O encontro registra uma etapa concreta da atuação territorial do TDS: apresentar a proposta, ouvir demandas locais e reunir referências para as formações seguintes. O número de 62 participantes se refere exclusivamente a essa reunião e não representa total de pessoas capacitadas, concluintes ou certificadas pelo programa.</p>
<!-- /wp:paragraph -->

