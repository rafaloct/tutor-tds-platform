<h2 class="wp-block-heading">Demanda das lideranças de Palmas vira formação em Associativismo e Cooperativismo</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Lideranças comunitárias de Palmas iniciaram uma formação em Associativismo e Cooperativismo na Escola de Tempo Integral Santa Bárbara. A atividade deu continuidade à escuta realizada com representantes comunitários no mês anterior.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A Prefeitura de Palmas registra <strong>61 inscritos</strong> no curso iniciado em 23 de junho de 2026 e informa continuidade das atividades nos dias 25 e 29 de junho. O número representa inscritos naquela formação específica e não deve ser tratado como total de concluintes, presentes ou certificados.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>A publicação municipal relaciona explicitamente a formação a uma demanda apresentada pelas lideranças no encontro de maio. A UFT também registra o primeiro dia do curso e destaca temas ligados à organização coletiva, participação social e desenvolvimento territorial.</p>
<!-- /wp:paragraph -->

